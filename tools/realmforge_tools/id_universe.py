"""The ID universe: every id that content may reference.

Sources, merged at validation time:
1. Vanilla snapshot ``tools/id_universe/vanilla-<mc>.json`` (generated by ``rf ids vanilla`` from the server jar).
2. NeoForge's own attributes (``NEOFORGE_ATTRIBUTES``): the loader is always there, so content may name them.
3. Our own ids from ``content/``.
4. TODO: a registry dump of the full modpack (Registry Dump mod), so content can reference ids from other mods.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

from realmforge_tools.project import MINECRAFT_VERSION, RepoPaths

# The attributes NeoForgeMod registers in the pinned NeoForge (26.1.2.116), read from its sources: check them when
# NeoForge's version changes (CLAUDE.md, pinned versions).
NEOFORGE_ATTRIBUTES: tuple[str, ...] = (
    "neoforge:creative_flight",
    "neoforge:nametag_distance",
    "neoforge:swim_speed",
)


@dataclass
class IdUniverse:
    """Known ids per registry (``minecraft:item`` -> {``minecraft:stick``, ...}) and known tags per registry."""

    registries: dict[str, set[str]] = field(default_factory=dict)
    tags: dict[str, set[str]] = field(default_factory=dict)

    def contains(self, registry: str, id_: str) -> bool:
        return id_ in self.registries.get(registry, set())

    def contains_tag(self, registry: str, tag: str) -> bool:
        return tag in self.tags.get(registry, set())

    def add(self, registry: str, id_: str) -> None:
        self.registries.setdefault(registry, set()).add(id_)


def vanilla_snapshot_path(paths: RepoPaths, version: str = MINECRAFT_VERSION) -> Path:
    return paths.id_universe / f"vanilla-{version}.json"


def load_vanilla(paths: RepoPaths, version: str = MINECRAFT_VERSION) -> IdUniverse:
    path = vanilla_snapshot_path(paths, version)
    if not path.exists():
        raise FileNotFoundError(f"{paths.rel(path)} is missing; run `uv run rf ids vanilla` to create it")
    data = json.loads(path.read_text(encoding="utf-8"))
    return IdUniverse(
        registries={name: set(ids) for name, ids in data["registries"].items()},
        tags={name: set(tags) for name, tags in data["tags"].items()},
    )
