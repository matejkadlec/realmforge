@pytest.mark.parametrize(
    ("name", "pixels", "width", "message"),
    [
        ("spell/frostbolt.png", _icon(32), 32, "is 32 x 32; this texture is 16 x 16"),
        ("effect/frozen.png", _icon(32), 32, "is 32 x 32; this texture is 18 x 18 or 16 x 16"),
        ("gui/spellbook_page.png", [ICE] * 256, 16, "is 16 x 16; this texture is 64 x 64"),
        ("gui/spellbook_cover.png", _icon(), 16, "a GUI part is a tile without transparent pixels"),
        ("spell/no_such_spell.png", _icon(), 16, "no spell has the id 'no_such_spell'"),
        ("item/no_such_item.png", _icon(), 16, "no item has the id 'no_such_item'"),
        ("gui/no_such_part.png", _icon(), 16, "no GUI part has the id 'no_such_part'"),
        ("spell/frostbolt.png", [(1, 2, 3, 255)] * 256, 16, "it has colours outside the project palette"),
        ("spell/frostbolt.png", [(140, 204, 244, 128)] * 256, 16, "it has half-transparent pixels"),
        (
            "block/vaultstone.png",
            _icon(),
            16,
            "approved art is art/textures/<item|spell|effect|gui>/<id>.png",
        ),
    ],
)
def test_validation_refuses_art_the_cleanup_did_not_write(
    art_repo: RepoPaths, name: str, pixels: list[Rgba], width: int, message: str
) -> None:
    _art(art_repo, name, pixels, width)
    problems = _problems(art_repo)
    assert len(problems) == 1
    assert problems[0].startswith(f"art/textures/{name}: ")
    assert message in problems[0]


