@pytest.fixture
def art_repo(repo: RepoPaths) -> RepoPaths:
    """The scratch checkout with the project palette, and no approved art yet."""
    palette = repo.root / DEFAULT_PALETTE
    palette.parent.mkdir(parents=True)
    shutil.copy(REPO_ROOT / DEFAULT_PALETTE, palette)
    return repo


def _art(repo: RepoPaths, name: str, pixels: list[Rgba], width: int = 16) -> Path:
    file = repo.root / "art" / "textures" / name
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_bytes(encode_rgba(width, len(pixels) // width, pixels))
    return file


def _icon(size: int = 16) -> list[Rgba]:
    """A diamond of two palette colours on a clear ground."""
    middle = (size - 1) / 2
    return [
        (ICE if abs(x - middle) + abs(y - middle) < size / 4 else DARK)
        if abs(x - middle) + abs(y - middle) < size / 2
        else CLEAR
        for y in range(size)
        for x in range(size)
    ]


def _generated(repo: RepoPaths) -> dict[str, bytes]:
    content, _ = load_and_validate(repo)
    return {repo.rel(path): data for path, data in generate_all(content, repo).items()}


def _problems(repo: RepoPaths) -> list[str]:
    with pytest.raises(ValidationFailed) as excinfo:
        load_and_validate(repo)
    return [str(problem) for problem in excinfo.value.problems]


def test_without_art_every_texture_is_its_placeholder(art_repo: RepoPaths) -> None:
    content, _ = load_and_validate(art_repo)
    files = {art_repo.rel(path): data for path, data in generate_all(content, art_repo).items()}
    assert not [name for name in files if name.startswith(f"{ASSETS}/textures/gui/sprites/spell/")]
    ruby = next(entry.model for entry in content.items if entry.model.id == "ruby")
    assert files[f"{ASSETS}/textures/item/ruby.png"] == placeholder_texture(
        "realmforge:ruby", int(ruby.color.removeprefix("#"), 16)
    )
    icons = files[
        "mod/src/generated/java/io/github/matejkadlec/realmforge/generated/GeneratedSpellIcons.java"
    ]
    assert "Set<String> SPELLS = Set.of();" in icons.decode()


def test_approved_art_takes_the_placeholders_place(art_repo: RepoPaths) -> None:
    icon = _icon()
    _art(art_repo, "spell/frostbolt.png", icon)
    _art(art_repo, "item/ruby.png", icon)
    files = _generated(art_repo)

    assert decode_rgba(files[f"{ASSETS}/textures/gui/sprites/spell/frostbolt.png"]) == (16, 16, icon)
    assert decode_rgba(files[f"{ASSETS}/textures/item/ruby.png"]) == (16, 16, icon)
    # A spell without art gets no sprite, and only the spells with one are listed for the client.
    assert f"{ASSETS}/textures/gui/sprites/spell/fireball.png" not in files
    listed = files[
        "mod/src/generated/java/io/github/matejkadlec/realmforge/generated/GeneratedSpellIcons.java"
    ]
    assert 'SPELLS = Set.of("frostbolt");' in listed.decode()


def test_generated_art_is_reencoded_whatever_wrote_the_file(art_repo: RepoPaths) -> None:
    """An image editor's PNG (compressed, another chunk layout) gives the same generated bytes as ours."""
    import struct
    import zlib

    icon = _icon()
    rows = b"".join(b"\x00" + b"".join(bytes(p) for p in icon[y * 16 : y * 16 + 16]) for y in range(16))

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

    compressed = (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", 16, 16, 8, 6, 0, 0, 0))
        + chunk(b"tEXt", b"Software\x00an editor")
        + chunk(b"IDAT", zlib.compress(rows, 9))
        + chunk(b"IEND", b"")
    )
    file = art_repo.root / "art" / "textures" / "spell" / "frostbolt.png"
    file.parent.mkdir(parents=True)
    file.write_bytes(compressed)

    assert _generated(art_repo)[f"{ASSETS}/textures/gui/sprites/spell/frostbolt.png"] == encode_rgba(
        16, 16, icon
    )


def test_a_small_effect_icon_is_centred_on_vanillas_size(art_repo: RepoPaths) -> None:
    icon = _icon()
    _art(art_repo, "effect/frozen.png", icon)
    width, height, pixels = decode_rgba(_generated(art_repo)[f"{ASSETS}/textures/mob_effect/frozen.png"])

    assert (width, height) == (18, 18)
    assert all(
        pixels[y * 18 + x] == CLEAR for y in range(18) for x in range(18) if x in (0, 17) or y in (0, 17)
    )
    assert [pixels[(y + 1) * 18 + x + 1] for y in range(16) for x in range(16)] == icon


