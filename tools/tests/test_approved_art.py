def test_the_gallery_marks_the_pick_and_cleans_a_subject_at_its_own_size(tmp_path: Path) -> None:
    palette = load_gpl(REPO_ROOT / DEFAULT_PALETTE)
    (tmp_path / "icon").mkdir()
    (tmp_path / "tile").mkdir()
    (tmp_path / "icon" / "a.png").write_bytes(encode_rgba(16, 16, _icon()))
    (tmp_path / "icon" / "b.png").write_bytes(encode_rgba(16, 16, _icon()))
    (tmp_path / "tile" / "a.png").write_bytes(encode_rgba(64, 64, [ICE] * 4096))
    (tmp_path / gallery.GALLERY_FILE).write_text(
        "subjects:\n  icon: {title: Icon, pick: b}\n  tile: {title: Tile, size: 64, pick: a}\n", "utf-8"
    )
    info, subjects = gallery.collect(tmp_path, palette, 16)

    tile = next(subject for subject in subjects if subject.name == "tile")
    assert (tile.candidates[0].cleaned.width, tile.candidates[0].report.scale) == (64, 1)
    page = gallery.render(info, subjects, palette)
    assert page.count('<span class="in-game">In the game</span>') == 2
    assert page.count('<article class="card picked">') == 2


def test_the_gallery_refuses_a_pick_that_is_no_candidate(tmp_path: Path) -> None:
    (tmp_path / "icon").mkdir()
    (tmp_path / "icon" / "a.png").write_bytes(encode_rgba(16, 16, _icon()))
    (tmp_path / gallery.GALLERY_FILE).write_text("subjects:\n  icon: {title: Icon, pick: z}\n", "utf-8")
    with pytest.raises(gallery.GalleryError, match=r"subjects\.icon\.pick: no candidate 'z'"):
        gallery.collect(tmp_path, load_gpl(REPO_ROOT / DEFAULT_PALETTE), 16)


def test_the_repositorys_picks_have_their_textures() -> None:
    """Each subject of the spell icon batch has a pick, and the texture that pick installed is there at the pick's
    size. The texture's pixels are not compared with the pick cleaned again: the palette is a living file (ADR 0023),
    so a new ramp may snap an old pick to other colours, and art that is in the game is not cleaned again for it. That
    the texture is clean is validation's check (``approved.problems``)."""
    batch = REPO_ROOT / "art" / "spell-icons" / "candidates"
    palette = load_gpl(REPO_ROOT / DEFAULT_PALETTE)
    info, _ = gallery.collect(batch, palette, 16)
    targets = {"effect_frozen": "effect/frozen", "effect_bleeding": "effect/bleeding"}
    targets |= {"book_page": "gui/spellbook_page", "book_cover": "gui/spellbook_cover"}
    assert all(subject.pick for subject in info.subjects.values())
    for name, subject in info.subjects.items():
        assert (batch / name / f"{subject.pick}.png").is_file(), name
        target = REPO_ROOT / "art" / "textures" / f"{targets.get(name, f'spell/{name}')}.png"
        width, height, _ = decode_rgba(target.read_bytes())
        assert (width, height) == (subject.size or 16, subject.size or 16), name
