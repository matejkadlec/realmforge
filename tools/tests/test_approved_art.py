def test_the_school_icons_are_drawn_in_palette_colours_with_their_gap() -> None:
    palette = {color.rgb for color in load_gpl(REPO_ROOT / DEFAULT_PALETTE).colors}
    for letter, rgba in school_icons.PIXELS.items():
        assert rgba[3] == 0 or rgba[:3] in palette, f"{letter!r} is not a palette colour"
    assert set(school_icons.ICONS) == {"fire", "frost", "arcane", "physical"}
    for school, rows in school_icons.ICONS.items():
        icon = school_icons.drawn_icon(school)
        assert icon is not None
        width, height, pixels = decode_rgba(icon)
        assert (width, height) == (8, 8)
        # The last column and row stay empty: the gap before the number the icon stands in front of.
        assert all(pixels[y * 8 + 7][3] == 0 for y in range(8)) and all(
            pixels[7 * 8 + x][3] == 0 for x in range(8)
        )
        assert sum(1 for pixel in pixels if pixel[3]) >= 12, f"{school}: too faint to read at 8 px"
        assert rows == tuple(rows), school
    assert school_icons.drawn_icon("holy") is None


def test_a_school_without_a_drawn_icon_keeps_its_placeholder(repo: RepoPaths) -> None:
    files = _generated(repo)
    for school in school_icons.ICONS:
        assert files[f"{ASSETS}/textures/gui/sprites/school/{school}.png"] == school_icons.drawn_icon(school)


def test_a_school_icon_must_keep_its_gap(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setitem(school_icons.ICONS, "fire", ("bbbbbbbb",) * 8)
    with pytest.raises(ValueError, match="last column and row stay empty"):
        school_icons.drawn_icon("fire")
    monkeypatch.setitem(school_icons.ICONS, "fire", ("bbb",) * 8)
    with pytest.raises(ValueError, match="not 8 rows of 8 pixels"):
        school_icons.drawn_icon("fire")


def test_the_spellbook_is_a_nine_slice_of_its_two_tiles(art_repo: RepoPaths) -> None:
    page = [ICE if (x + y) % 2 else DARK for y in range(64) for x in range(64)]
    cover = [(66, 47, 29, 255)] * 256  # wood 3
    _art(art_repo, "gui/spellbook_page.png", page, width=64)
    _art(art_repo, "gui/spellbook_cover.png", cover)
    files = _generated(art_repo)

    width, height, pixels = decode_rgba(files[f"{ASSETS}/textures/gui/sprites/spellbook/book.png"])
    assert (width, height) == (spellbook.WIDTH, spellbook.HEIGHT) == (88, 84)
    # The page fills the middle slice, pixel for pixel, so the game can repeat it without a seam.
    middle = [
        pixels[(spellbook.EDGE + y) * width + spellbook.SPINE + x] for y in range(64) for x in range(64)
    ]
    assert middle == page
    # The cover runs round it: an outline with cut corners, leather inside it, the spine wider than the edges.
    assert pixels[0] == CLEAR and pixels[width - 1] == CLEAR and pixels[-1] == CLEAR
    assert pixels[width // 2] == spellbook.OUTLINE
    assert pixels[3 * width + width // 2] == cover[0]
    assert pixels[(height // 2) * width + 6] == cover[0]
    assert all(pixel[3] == 255 for pixel in pixels[width : 2 * width - 1][1:])

    scaling = json.loads(files[f"{ASSETS}/textures/gui/sprites/spellbook/book.png.mcmeta"])["gui"]["scaling"]
    assert scaling == {
        "type": "nine_slice",
        "width": 88,
        "height": 84,
        "border": {"left": 14, "top": 10, "right": 10, "bottom": 10},
    }
    # The edges repeat too: the top edge's rows are the same at both ends of the middle slice's width.
    for y in range(spellbook.EDGE):
        row = pixels[y * width + spellbook.SPINE : y * width + spellbook.SPINE + 64]
        assert row[:16] == row[16:32] == row[48:64], (
            f"row {y} of the top edge does not repeat every 16 pixels"
        )


